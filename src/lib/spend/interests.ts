import type { CategoryId } from "./model";

/*
 * The kinds of thing people buy, finer than the spending categories.
 * Pence maps every shop and every receipt line to one of these, so it can
 * tell perfume from paracetamol even when both came from Boots.
 */

export type InterestDef = {
  id: string;
  /** Short label for a chip or heading. */
  label: string;
  /** How the interest reads inside a sentence: "You've spent £40 on {noun}". */
  noun: string;
  /** What the person does, after "You": "take taxis". Defaults to "buy {noun}". */
  verb?: string;
  category: CategoryId;
  /** Shop names, matched against the merchant only. "=word" must be the first word of the merchant. */
  shops: string[];
  /** Product words, matched against receipt line items only. */
  items: string[];
  /** Search words for public deal boards. Empty means the habit is shown but not searched. */
  query: string;
  /** A deal title must contain one of these to count for this interest. */
  match: string[];
  /** A deal title with any of these is off-topic for this interest. */
  avoid: string[];
  /** Line items here name a product worth searching on its own. */
  products?: boolean;
  /** The shops sell many kinds of thing, so the category the person chose wins. */
  broad?: boolean;
  /** Other shops or services for the same thing, where the same spend could cost less. */
  rivals?: string[];
};

